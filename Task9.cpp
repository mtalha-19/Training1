#include <iostream>
using namespace std;;
int main()
{
    int  a, b;
    cout<<"Enter two numbers ";
    cin >> a >> b;
    
    cout << "sum = "      << a + b << endl;
    cout << "Subtract = " << a - b << endl;
    cout << "Multiple = " << a * b << endl;
    cout << "Divide = "   << a / b << endl;
    cout << "Mode = "     << a % b << endl;

    return 0;
}